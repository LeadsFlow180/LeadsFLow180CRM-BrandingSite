import fs from "node:fs";
import path from "node:path";

/**
 * Scans public/agents/videos for {agentId}.mp4|webm|mov and writes src/lib/agentVideos.ts.
 * Drop a file named after the agent id (e.g. jay.mp4, mia.mp4) — no other wiring needed.
 */
const dir = path.join(process.cwd(), "public", "agents", "videos");
const outFile = path.join(process.cwd(), "src", "lib", "agentVideos.ts");

fs.mkdirSync(dir, { recursive: true });

const files = fs
  .readdirSync(dir)
  .filter((f) => /\.(mp4|webm|mov)$/i.test(f))
  .sort((a, b) => a.localeCompare(b));

const lines = files.map((f) => {
  const id = f.replace(/\.(mp4|webm|mov)$/i, "").toLowerCase();
  return `  ${JSON.stringify(id)}: ${JSON.stringify(`/agents/videos/${f}`)},`;
});

const source = `/** Auto-generated by npm run sync:videos — do not edit by hand.
 * Drop {agentId}.mp4 (or .webm/.mov) into public/agents/videos/ then run sync (or npm run dev/build).
 */
export const agentVideos: Record<string, string> = {
${lines.join("\n")}
};

export function getAgentVideo(id: string): string | undefined {
  return agentVideos[id];
}
`;

fs.writeFileSync(outFile, source, "utf8");
console.log(`Synced ${files.length} agent video(s) → src/lib/agentVideos.ts`);
